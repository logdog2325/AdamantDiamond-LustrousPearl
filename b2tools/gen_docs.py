"""The player guide of Pokémon Adamant Diamond & Lustrous Pearl: Markdown pages made from the project's own data, so a release
regenerates them instead of anyone editing them by hand (HoennB2's b2tools/gen_docs.py is the model).

    python3 b2tools/gen_docs.py [OUT_DIR]      (default docs/, next to docs/screenshots)

RERUN THIS after anything that changes what a page states (wild tables, scripts, the feature data files) and before a
release, and commit docs/ with the change: the pages are not rebuilt by a ROM build. The generator stops (need(), number())
when a script or C file no longer has what a page states, so a stale statement fails here instead of reaching players.

Each version's data is read in its own process (PEARL_VERSION is read once, by b2tools/version.py):
    main -> this script --part, once per version -> wild-pokemon, items, trainers, postgame, ramanas-park (-pearl, -diamond)
    main itself -> the pages both versions share.

Pages and what each reads:
  wild-pokemon-<v>   work/<v>/encounters + zones.json (gen4_extract, what patches/sinnoh_encounters.py installs: time of day,
                     rods), patches/wild.py (swarms, honey trees, the Great Marsh, Feebas), data/underground_pokemon.json
  items-<v>          pearl_items.world() (balls, hidden items), Pearl's berry patches (pearl_events, patches/wild.py),
                     data/underground.json (the Hideaways' balls, grottos)
  trainers-<v>       work/pearl/b2_trainers/data (sinnoh_trainers.py: what patches/pearl_trainers.py installs) and the scripts'
                     PTRAINER_n (which battle where)
  postgame-<v>       src/field_scripts, patches/roamers.py, notes/BATTLE_ZONE.md's tables as the C has them
  ramanas-park-<v>   data/ramanas_park.json, src/field_scripts/1901_ramanas_rooms.s (the version's)
  underground, secret-bases, super-contests, poffins, poketch, levels, options, fairy-type, tms-and-hms, evolutions,
  known-issues, README
No images and no ROM data but these facts."""
