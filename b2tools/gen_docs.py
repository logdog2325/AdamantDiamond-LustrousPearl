def _berry_patches(names):
    """{map name: [berry names]} of Pearl's soil patches as a new game has them (pearl_events, patches/wild.py)."""
    import pearl_story, pearl_events, wild
    pd = pearl_story.PearlData()
    start = wild.new_game_patches(wild._rom())
    out, seen = collections.defaultdict(list), set()
    for z in pd.zones:
        if z['events'] in seen or z['id'] not in built_zones():
            continue
        seen.add(z['events'])
        for o in pd.events(z)['object_events']:
            if pearl_events.is_berry_patch(o):
                n = o['data'][0]
                berry, _ = start[n]
                out[z['name']].append(names.item(wild.FIRST_BERRY_ITEM + berry - 1))
    assert sum(map(len, out.values())) == wild.PATCHES, sum(map(len, out.values()))
    return out

