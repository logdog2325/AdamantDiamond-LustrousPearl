# ---- output -----------------------------------------------------------------------------------------------------------
FORBIDDEN = re.compile(r'Platinum(?! Flag)|\bagents?\b|\bsessions?\b|\bAI\b|Claude|Anthropic|DECISIONS|notes/|b2tools/(?!gen_docs)|pokeplatinum|pokediamond|Serebii|Bulbapedia|decomp\b', re.I)

def write(out, name, text):
    if not text.startswith('<!-- Generated by'):
        raise SystemExit(f'gen_docs: {name} has no "Generated by" comment')
    for k, line in enumerate(text.split('\n'), 1):
        if k == 1:
            continue
        m = FORBIDDEN.search(line)
        if m:
            raise SystemExit(f'gen_docs: {name} line {k} says {m.group(0)!r}: {line[:120]}')
    with open(os.path.join(out, name), 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', name, len(text), 'B')

def check_links(out):
    """Every link between pages resolves (the file, and its heading if the link names one)."""
    bad = []
    for p in sorted(glob.glob(os.path.join(out, '*.md'))):
        text = open(p, encoding='utf-8').read()
        for label, target in re.findall(r'\[([^\]]+)\]\(([^)]+)\)', text):
            if target.startswith('http'):
                continue
            f, _, frag = target.partition('#')
            q = os.path.join(out, f) if f else p
            if not os.path.exists(q):
                bad.append((os.path.basename(p), target))
                continue
            if frag:
                heads = [anchor(h) for h in re.findall(r'^#+ (.*)$', open(q, encoding='utf-8').read(), re.M)]
                if frag not in heads:
                    bad.append((os.path.basename(p), target))
    if bad:
        raise SystemExit(f'gen_docs: {len(bad)} broken links, first: {bad[:6]}')

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    out = os.path.abspath(args[0] if args else os.path.join(ROOT, 'docs'))
    os.makedirs(out, exist_ok=True)
    if '--part' in sys.argv:                     # one version's pages (PEARL_VERSION set by the caller)
        names = Names()
        v = version.VERSION
        write(out, f'wild-pokemon-{v}.md', wild_page(names))
        write(out, f'items-{v}.md', items_page(names))
        write(out, f'trainers-{v}.md', trainers_page(names))
        write(out, f'postgame-{v}.md', postgame_page(names))
        write(out, f'ramanas-park-{v}.md', ramanas_page(names))
        return
    for v in version.VERSIONS:
        subprocess.run([sys.executable, os.path.abspath(__file__), out, '--part'], check=True,
                       env=dict(os.environ, PEARL_VERSION=v))
    names = Names()
    write(out, 'levels.md', levels_page())
    write(out, 'options.md', options_page())
    write(out, 'fairy-type.md', fairy_page(names))
    write(out, 'evolutions.md', evolutions_page(names))
    write(out, 'tms-and-hms.md', tms_page(names))
    write(out, 'underground.md', underground_page(names))
    write(out, 'secret-bases.md', secret_bases_page(names))
    write(out, 'super-contests.md', contests_page())
    write(out, 'poffins.md', poffins_page(names))
    write(out, 'poketch.md', poketch_page())
    write(out, 'known-issues.md', known_issues_page(names))
    write(out, 'README.md', index_page())
    check_links(out)

if __name__ == '__main__':
    main()
