def encounter_file(n):
    return json.load(open(os.path.join(version.WORK, 'encounters', f'{n:03d}.json')))

def _label(names, enc, sp):
    n = names.species(sp)
    if sp == 'SPECIES_SHELLOS' and enc['rate_form0'] or sp == 'SPECIES_GASTRODON' and enc['rate_form1']:
        return n + ' (East Sea)'
    if sp == 'SPECIES_UNOWN' and enc['unown_table']:
        import sinnoh_encounters as enc_mod
        forms = enc_mod.UNOWN_FORMS.get(enc['unown_table'])
        if forms:
            letters = ['!' if f == 26 else '?' if f == 27 else chr(65 + f) for f in forms]
            return f'{n} ({" and ".join(letters)})'
        return f'{n} (any letter)'
    return n

def _period_table(names, enc):
    """Rows of the grass table: {label: [lo, hi, morning %, day %, night %]}, as patches/sinnoh_encounters.py grass_slots
    installs it (slots 2-3 by the time of day)."""
    import sinnoh_encounters as enc_mod
    rows = collections.OrderedDict()
    for p, period in enumerate(('morning', 'day', 'night')):
        for (sp, _, lo, hi), odds in zip(enc_mod.grass_slots(enc, period), GRASS):
            r = rows.setdefault(_label(names, enc, sp), [lo, hi, 0, 0, 0])
            r[0], r[1] = min(r[0], lo), max(r[1], hi)
            r[2 + p] += odds
    return rows

def _lv(lo, hi):
    return f'{lo}' if lo == hi else f'{lo}-{hi}'

def _water(names, enc, key, odds):
    rows = collections.OrderedDict()
    for s, o in zip(enc[key], odds):
        r = rows.setdefault(_label(names, enc, s['species']), [s['level_min'], s['level_max'], 0])
        r[0], r[1], r[2] = min(r[0], s['level_min']), max(r[1], s['level_max']), r[2] + o
    return sorted(rows.items(), key=lambda kv: -kv[1][2])

def area_tables(names):
    """[(place names, map names, the area's sections)] of every built zone with wild Pokémon, zones with the same tables
    together."""
    import wild
    swarm_ids, seen = set(wild.SWARM_MAPS), collections.OrderedDict()
    built = built_zones()
    for z in zones():
        if z['encounters'] is None or (z['id'] not in built and 'TURNBACK' not in z['name']):
            continue
        e = encounter_file(z['encounters'])
        # the Great Marsh, the Trophy Garden and swarms keep their own notes: their zones aren't merged with others
        key = json.dumps({k: e[k] for k in ('land_rate', 'land_encounters', 'day', 'night', 'surf_rate', 'surf_encounters',
                                            'old_rod_rate', 'old_rod_encounters', 'good_rod_rate', 'good_rod_encounters',
                                            'super_rod_rate', 'super_rod_encounters', 'rate_form0', 'rate_form1', 'unown_table')})
        key += json.dumps(e['swarms'] if z['id'] in swarm_ids else None)
        seen.setdefault(key, (e, []))[1].append(z)
    out = []
    for e, zs in seen.values():
        if not any(e[k] for k in ('land_rate', 'surf_rate', 'old_rod_rate', 'good_rod_rate', 'super_rod_rate')):
            continue
        out.append((e, sorted(zs, key=lambda z: place_key(z['name']))))
    out.sort(key=lambda t: place_key(t[1][0]['name']))
    return out, swarm_ids

def _area_title(zs, enc=None):
    seen = []
    for z in zs:
        p = place(z['name'])
        if p not in seen:
            seen.append(p)
    title = ' / '.join(seen)
    if title == 'Turnback Cave' and enc:
        # Pearl's three tiers (b2tools/turnback.py: by pillars seen), the same species
        lv = enc['land_encounters'][0]['level']
        tier = {45: 'no pillar seen yet', 55: 'one pillar seen', 65: 'two pillars seen'}.get(lv)
        if not tier:
            raise SystemExit(f'gen_docs: a Turnback Cave table starts at level {lv}: update _area_title')
        return f'Turnback Cave, {tier}'
    if title == 'Lake Verity' and zs[0]['name'] == 'MAP_LAKE_VERITY_GALACTIC':       # Pearl's two maps of the lake; only this one has a swarm
        return title + ', after Team Galactic arrives'
    return title

def _hours():
    """The game's hours for its three wild tables, by season: src/system/rtc.c day_part, as src/code/time_encounters.c reads it
    (morning: the morning table; day and evening: the day table; night and midnight: the night table)."""
    src = read('external/pokebw2/src/system/rtc.c')
    parts = re.findall(r'DAY_PERIOD_(MORNING|DAY|EVENING|NIGHT|MIDNIGHT)\b', src[src.index('day_part'):src.index('u16 GetRealTimeDayPeriod')])
    if len(parts) != 96:
        raise SystemExit(f'gen_docs: rtc.c day_part has {len(parts)} hours: update _hours')
    kind = {'MORNING': 'morning', 'DAY': 'day', 'EVENING': 'day', 'NIGHT': 'night', 'MIDNIGHT': 'night'}
    out = []
    for season, row in zip(('spring', 'summer', 'autumn', 'winter'), (parts[i:i + 24] for i in range(0, 96, 24))):
        row = [kind[x] for x in row]
        said = []
        for k in ('morning', 'day', 'night'):
            first = next(h for h in range(24) if row[h] == k and row[h - 1] != k)
            last = next(h for h in range(first, first + 24) if row[(h + 1) % 24] != k) % 24
            said.append(f'{first}:00-{last}:59 {k}')
        out.append(f'{season} {", ".join(said)}')
    return '; '.join(out)

