@functools.lru_cache(maxsize=1)
def _towns():
    """Map name -> the game's place name for towns and cities (data/sinnoh_places.json, by Pearl's map section)."""
    pl = json.load(open(os.path.join(ROOT, 'data', 'sinnoh_places.json'), encoding='utf-8'))['lines']
    out = {}
    for z in zones():
        name = pl.get(str(z['mapsec'] + 153), '')
        if re.fullmatch(r'[A-Z][a-z]+ (Town|City)', name) and z['name'][4:] == name.split()[0].upper().replace('JUBILIFE', 'JUBLIFE'):
            out[z['name']] = name
    return out

def place(map_name):
    """MAP_ROUTE_204_SOUTH -> Route 204 South, MAP_JUBLIFE -> Jubilife City."""
    towns = _towns()
    if map_name in towns:
        return towns[map_name]
    words = [PLACE_TOKENS.get(w, w if re.fullmatch(r'B?\d+F|\d+', w) else w.capitalize()) for w in map_name[4:].split('_')]
    s = ' '.join(words)
    for pat, rep in PLACE_FIX:
        s = re.sub(pat, rep, s)
    return s

def place_key(map_name):
    """Routes in number order first, then everything else alphabetically."""
    m = re.match(r'MAP_ROUTE_(\d+)', map_name)
    if m and 'LOST_TOWER' not in map_name:
        return (0, int(m.group(1)), map_name)
    return (1, 0, place(map_name), map_name)

@functools.lru_cache(maxsize=1)
def zones():
    return json.load(open(os.path.join(version.WORK, 'zones.json')))

@functools.lru_cache(maxsize=1)
def built_zones():
    """Pearl zone ids this game has (data/sinnoh_world.json), with the Turnback Cave rooms that share a zone
    (b2tools/turnback.py: each zone holds two of Pearl's rooms; a table is the same for both)."""
    w = json.load(open(os.path.join(ROOT, 'data', 'sinnoh_world.json')))
    ids = {int(k) for k in w['zones']} | {int(k) for k in w['rooms']['zones']}
    return ids

