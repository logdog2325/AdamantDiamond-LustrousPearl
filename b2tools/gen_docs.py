# ---- stop-checks: what a page states must still be in the source -----------------------------------------------------
def read(rel):
    return open(os.path.join(ROOT, rel), encoding='utf-8').read()

def script(rel):
    """A field script source as this version builds it (src/field_scripts/diamond/ replaces a file of the same name)."""
    p = os.path.join(FS, rel)
    d = os.path.join(FS, 'diamond', rel)
    return open(d if version.DIAMOND and os.path.exists(d) else p, encoding='utf-8').read()

def need(rel, *texts, page='the guide'):
    """Stop when a source no longer has what a page states."""
    s = read(rel)
    for t in texts:
        if t not in s:
            raise SystemExit(f'gen_docs: {rel} no longer has {t!r}: update {page}')

def number(rel, pattern, page='the guide', base=0):
    """The first group of pattern in a source, as a number (stops when it's gone)."""
    m = re.search(pattern, read(rel))
    if not m:
        raise SystemExit(f'gen_docs: {rel} has no {pattern!r} any more: update {page}')
    return int(m.group(1), base)

def join(xs, word='and'):
    xs = list(xs)
    if len(xs) < 2:
        return ''.join(xs)
    return ', '.join(xs[:-1]) + f' {word} ' + xs[-1]

def clean(line):
    """A line of game text for a page: no control codes, line breaks as spaces."""
    line = re.sub(r'\{[^}]*\}', '', line or '')
    return re.sub(r'\s+', ' ', line.replace('\\n', ' ').replace('\\r', ' ').replace('\\f', ' ')).strip()

def anchor(s):
    return re.sub(r'[^a-z0-9é _-]', '', s.lower()).replace(' ', '-')


# ---- names: what the game shows (Black 2's text, the project's overrides) -------------------------------------------
def _constants(header, prefix):
    return {k: int(v) for k, v in re.findall(rf'#define ({prefix}\w+)\s+(\d+)', open(os.path.join(PCONST, header)).read())}

class Names:
    def __init__(self):
        self.species_id = _constants('species.h', 'SPECIES_')
        self.items_id = _constants('items.h', 'ITEM_')
        self.moves_id = _constants('moves.h', 'MOVE_')
        self.species_c = {v: k for k, v in reversed(list(self.species_id.items()))}
        self.items_c = {v: k for k, v in reversed(list(self.items_id.items()))}
        self.moves_c = {v: k for k, v in reversed(list(self.moves_id.items()))}
        self.over = {}
        self.move_over = {}
        for p in glob.glob(os.path.join(ROOT, 'data', 'text_overrides', '*.json')):
            for k, v in json.load(open(p, encoding='utf-8')).items():
                m = re.fullmatch(r'res/items/(\w+)/data\.json', k)
                if m and 'name' in v:
                    self.over[m.group(1)] = v['name']
        import tm_audit
        self.machines = tm_audit.machines()

    def _json(self, kind, const, prefix):
        p = os.path.join(B2, 'res', kind, const[len(prefix):].lower(), 'data.json')
        return json.load(open(p, encoding='utf-8'))['name'] if os.path.exists(p) else None

    @functools.lru_cache(maxsize=None)
    def species(self, s):
        """By constant or number."""
        c = s if isinstance(s, str) else self.species_c[s]
        if c not in self.species_id:
            raise SystemExit(f'gen_docs: {c} is not a Black 2 species')
        n = self._json('pokemon', c, 'SPECIES_')
        if not n:
            raise SystemExit(f'gen_docs: no name for {c}')
        return n

    @functools.lru_cache(maxsize=None)
    def item(self, i, tm_move=True):
        """By constant or number; a TM or HM with its move."""
        num = i if isinstance(i, int) else self.items_id[i]
        if num in self.machines and tm_move:
            label, mv, _ = self.machines[num]
            return f'{label} {self.move(mv)}'
        c = self.items_c[num]
        d = c[len('ITEM_'):].lower()
        if d in self.over:
            return self.over[d]
        n = self._json('items', c, 'ITEM_')
        if not n:
            # 113, 114 and the shards' ids carry unused_N names in the decomp
            d = f'unused_{num}'
            n = self.over.get(d)
        if not n:
            raise SystemExit(f'gen_docs: no name for item {i} ({c})')
        return n

    @functools.lru_cache(maxsize=None)
    def move(self, m):
        c = m if isinstance(m, str) else self.moves_c[m]
        n = self._json('moves', c, 'MOVE_')
        if not n:
            raise SystemExit(f'gen_docs: no name for {c}')
        return n


