def bitmap_ncgr(d):
    o = _sec(d, b'RAHC')
    h, w, bd, _, flags, sz, off = struct.unpack_from('<HHIIIII', d, o + 8)
    assert bd == 3 and sz == w * h * 32, (w, h, bd, sz)
    if not flags & 1:
        return d
    raw = d[o + 8 + off:o + 8 + off + sz]
    tiles = bytearray()
    for row in range(h):
        for col in range(w):
            for line in range(8):
                at = (row * 8 + line) * w * 4 + col * 4
                tiles += raw[at:at + 4]
    rahc = b'RAHC' + struct.pack('<IHHIIIII', 0x20 + len(tiles), h, w, 3, 0, 0, len(tiles), 0x18) + bytes(tiles)
    sopc = b'SOPC' + struct.pack('<IIHH', 0x10, 0, w, h)
    body = rahc + sopc
    return b'RGCN' + struct.pack('<HHIHH', 0xFEFF, 0x0101, 0x10 + len(body), 0x10, 2) + body


def batter_ncgr(d):
    """Pearl's batter for each phase, a 128 x 128 bitmap for a 3D sprite: the same pixels as four 64 x 64 blocks of OBJ tiles."""
    o = _sec(d, b'RAHC')
    h, w, bd, _, flags, sz, off = struct.unpack_from('<HHIIIII', d, o + 8)
    assert (w, h, bd, sz) == (16, 16, 3, 8192) and flags & 1, (w, h, bd, flags, sz)
    raw = d[o + 8 + off:o + 8 + off + sz]
    tiles = bytearray()
    for by in (0, 8):
        for bx in (0, 8):
            for row in range(8):
                for col in range(8):
                    for line in range(8):
                        at = ((by + row) * 8 + line) * 64 + (bx + col) * 4
                        tiles += raw[at:at + 4]
    rahc = b'RAHC' + struct.pack('<IHHIIIII', 0x20 + len(tiles), 16, 16, 3, 0, 0, len(tiles), 0x18) + bytes(tiles)
    sopc = b'SOPC' + struct.pack('<IIHH', 0x10, 0, 16, 16)
    body = rahc + sopc
    return b'RGCN' + struct.pack('<HHIHH', 0xFEFF, 0x0101, 0x10 + len(body), 0x10, 2) + body


def cells_1d32(d):
    """Pearl's cell file, its characters named in steps of its own mapping, for Black 2's OBJ mode (1D, 32 B a name: the Contest
    screens' VRAM set-up): the same tiles, the names in single tiles."""
    o = _sec(d, b'KBEC')
    n, flags, off, mapping = struct.unpack_from('<HHII', d, o + 8)
    if mapping == 0:
        return d
    d = bytearray(d)
    size = 16 if flags & 1 else 8
    cells = o + 8 + off
    oams = cells + n * size
    for c in range(n):
        count, _, at = struct.unpack_from('<HHI', d, cells + c * size)
        for j in range(count):
            p = oams + at + 6 * j + 4
            a2 = struct.unpack_from('<H', d, p)[0]
            name = (a2 & 0x3ff) << mapping
            assert name < 0x400
            struct.pack_into('<H', d, p, (a2 & 0xfc00) | name)
    struct.pack_into('<I', d, o + 8 + 8, 0)
    return bytes(d)


def batter_ncer():
    shape, size = 0, 3      # square, 64 x 64
    oams = b''.join(struct.pack('<HHH', (y & 0xff) | shape << 14, (x & 0x1ff) | size << 14, i * 64)
                    for i, (x, y) in enumerate(((-63, -63), (0, -63), (-63, 0), (0, 0))))   # (a pixel of overlap: rotated, the blocks' rounding leaves seams)
    kbec = struct.pack('<HHIIIII', 1, 0, 0x18, 0, 0, 0, 0) + struct.pack('<HHI', 4, 23, 0) + oams
    while len(kbec) % 4:
        kbec += b'\0'
    block = b'KBEC' + struct.pack('<I', 8 + len(kbec)) + kbec
    return b'RECN' + struct.pack('<HHIHH', 0xFEFF, 0x0100, 0x10 + len(block), 0x10, 1) + block


def clip_ncer():
    oams, heads = bytearray(), b''
    for w, h in CLIP_SIZES:
        shape, size = OBJ_SHAPE[(w, h)]
        x, y = -w // 2, -h // 2
        heads += struct.pack('<HHI', 1, (max(w, h) // 2 + 3) // 4 & 0x3f, len(oams))
        oams += struct.pack('<HHH', (y & 0xff) | shape << 14, (x & 0x1ff) | size << 14, 0)
    kbec = struct.pack('<HHIIIII', len(CLIP_SIZES), 0, 0x18, 0, 0, 0, 0) + heads + bytes(oams)
    while len(kbec) % 4:
        kbec += b'\0'
    block = b'KBEC' + struct.pack('<I', 8 + len(kbec)) + kbec
    return b'RECN' + struct.pack('<HHIHH', 0xFEFF, 0x0100, 0x10 + len(block), 0x10, 1) + block


def clip_nanr(count=None):
    count = count or len(CLIP_SIZES)
    seq = b''.join(struct.pack('<HHIII', 1, 0, 0x00010000, 1, i * 8) for i in range(count))
    frames = b''.join(struct.pack('<IHH', i * 4, 4, 0xBEEF) for i in range(count))
    results = b''.join(struct.pack('<HH', i, 0xCCCC) for i in range(count))
    head = struct.pack('<HHIIIII', count, count, 0x18, 0x18 + len(seq), 0x18 + len(seq) + len(frames), 0, 0)
    body = head + seq + frames + results
    block = b'KNBA' + struct.pack('<I', 8 + len(body)) + body
    return b'RNAN' + struct.pack('<HHIHH', 0xFEFF, 0x0100, 0x10 + len(block), 0x10, 1) + block


