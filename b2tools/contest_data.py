def move_ids():
    """Move constant name -> id, by pokebw2's generated/moves.txt (its first code line is MOVE_NONE = 0)."""
    ids = {}
    at = 0
    for line in open(os.path.join(DECOMP, 'generated', 'moves.txt')):
        line = line.strip()
        if not line.startswith('MOVE_'):
            continue
        name = line.split()[0][5:]
        ids[name] = at
        at += 1
    return ids


def move_table(rom):
    """Per move 0..MOVE_COUNT-1 the bytes (contest type, contest effect): Pearl's waza_tbl (offset 12 effect, 13 type) for
    1-467, NEW_MOVES for the rest."""
    members = narc_members(rom.read('poketool/waza/waza_tbl.narc'))
    ids = move_ids()
    table = [(m[13], m[12]) for m in members[:468]]
    for move in range(468, MOVE_COUNT):
        pearl_id = ids[NEW_MOVES[move]]
        assert 0 < pearl_id < 468, f'{NEW_MOVES[move]} = {pearl_id}'
        table.append(table[pearl_id])
    assert len(table) == MOVE_COUNT
    return b''.join(bytes(t) for t in table)


