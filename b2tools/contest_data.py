def overlay(rom, n):
    off, _ = struct.unpack_from('<II', rom.data, 0x50)
    idn, ram, size, bss, s, e, fid, fl = struct.unpack_from('<8I', rom.data, off + 32 * n)
    assert idn == n
    st, en = rom.fat[fid]
    return ram, rom.data[st:en]


def write_inc():
    ram, o = overlay(pearl(), 12)
    assert ram == OV12_RAM
    rows = []
    for i in range(AI_ROWS):
        pos, cond, target, mode, a, b, c, d = struct.unpack_from('<BBBb4h', o, AI_ROWS_AT - ram + 12 * i)
        rows.append(f'    {{ {pos}, {cond}, {target}, {mode}, {{ {a}, {b}, {c}, {d} }} }},')
    head = '// Generated by b2tools/contest_data.py inc from Pearl\'s overlay 12: don\'t edit.\n'
    text = head + f'static const AIRow sAIRows[{AI_ROWS}] = {{\n' + '\n'.join(rows) + '\n};\n'
    open(os.path.join(DECOMP, 'src', 'pearlb2', 'contest', 'contest_ai_rows.inc'), 'w').write(text)
    rows = []
    for i in range(SONGS):
        song, bpm, a, b, c, d, w0, w1, w2, w3 = struct.unpack_from('<HH8B', o, SONGS_AT - ram + 12 * i)
        rows.append(f'    {{ {song:#x}, {bpm}, {a}, {b}, {c}, {d}, {{ {w0}, {w1}, {w2}, {w3} }} }},')
    text = head + f'static const DanceSong sDanceSongs[{SONGS}] = {{\n' + '\n'.join(rows) + '\n};\n'
