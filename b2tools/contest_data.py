def platinum_effects():
    """Platinum's Unk_020F568C (unk_02094EDC.c), by effect: the two description lines, the points, the five lines of bank
    198 with their name-slots. contest_check compares the numbers with Pearl's arm9."""
    import re
    src = open(os.path.join(PLATINUM, 'src', 'unk_02094EDC.c')).read()
    ids = {m[0]: i for i, m in enumerate(text_ids('contest_effects'))}
    body = re.search(r'Unk_020F568C\[CONTEST_EFFECT_MAX\] = \{(.*?)\n\};', src, re.S).group(1)
    rows = []
    for e in re.finditer(r'\[(CONTEST_EFFECT_\w+)\] = \{(.*?)\n    \}', body, re.S):
        f = [x.strip() for x in e.group(2).split(',') if x.strip()]
        vals = [ids[x] if x in ids else int(x, 0) for x in f]
        vals += [0xffff, 0] * 8
        rows.append((e.group(1), vals[:13]))
    return rows


def rewards():
    """Platinum's Contest_CalcFirstTimeVictoryAccessoryReward as [type][rank] ids of Pearl's accessory names (bank 338: the
    names match, so Platinum's ids don't have to)."""
    import re, gen4_text
    src = open(os.path.join(PLATINUM, 'src', 'contest.c')).read()
    body = src[src.index('Contest_CalcFirstTimeVictoryAccessoryReward'):]
    body = body[:body.index('GF_ASSERT(accessoryID != ACCESSORY_COUNT)')]
    names = {l.lower(): k for k, l, e in gen4_text.convert_bank(338, PEARL)}
    found = re.findall(r'accessoryID = ACCESSORY_(\w+);', body)[1:]
    assert len(found) == 20, found
    def by_name(n):
        n = n.replace('_', ' ').lower()
        return names[n] if n in names else names[n[:-1] if n.endswith('s') else n + 's']
    ids = [by_name(n) for n in found]
    return [ids[t * 4:t * 4 + 4] for t in range(5)]


