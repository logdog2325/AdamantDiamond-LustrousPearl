def blob(path):
    """opponents, judges, dresses, 12 theme rows, moves: [count u32, size u32] + bytes each, for sim.c"""
    rom = pearl()
    m = narc_members(rom.read('contest/data/contest_data.narc'))
    parts = [m[0], m[1], m[2], b''.join(m[3:15]), move_table(rom)]
    out = b''
    for p in parts:
        out += struct.pack('<I', len(p)) + p
    open(path, 'wb').write(out)
    return [len(p) for p in parts]


