def _sec(d, name):
    o = struct.unpack_from('<H', d, 0xc)[0]
    while o < len(d):
        if d[o:o + 4] == name:
            return o
        o += struct.unpack_from('<I', d, o + 4)[0]
    raise ValueError(name)


