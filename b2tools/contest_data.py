OBJ_SHAPE = {(16, 16): (0, 1), (32, 32): (0, 2), (32, 16): (1, 2), (64, 32): (1, 3), (16, 32): (2, 2), (32, 64): (2, 3)}
CLIP_SIZES = ((16, 16), (32, 32), (64, 32), (32, 64), (16, 32), (32, 16))     # the cells' order: contest_visual.c


def clip_ncgr(d):
    """An Accessory: Pearl's NCGR holds a linear bitmap for its 3D sprite; Black 2's cell actors want tiles in OBJ order.
    The same pixels: returns (the file, its cell number)."""
    o = _sec(d, b'RAHC')
    h, w, bd, _, flags, sz, off = struct.unpack_from('<HHIIIII', d, o + 8)
    assert bd == 3 and flags & 1 and sz == w * h * 32, (w, h, bd, flags, sz)
    raw = d[o + 8 + off:o + 8 + off + sz]
    tiles = bytearray()
    for row in range(h):
        for col in range(w):
            for line in range(8):
                at = (row * 8 + line) * w * 4 + col * 4
                tiles += raw[at:at + 4]
    rahc = b'RAHC' + struct.pack('<IHHIIIII', 0x20 + len(tiles), h, w, 3, 0, 0, len(tiles), 0x18) + bytes(tiles)
    sopc = b'SOPC' + struct.pack('<IIHH', 0x10, 0, w, h)
    body = rahc + sopc
    return b'RGCN' + struct.pack('<HHIHH', 0xFEFF, 0x0101, 0x10 + len(body), 0x10, 2) + body, CLIP_SIZES.index((w * 8, h * 8))


